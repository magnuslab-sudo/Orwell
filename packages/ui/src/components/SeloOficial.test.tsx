import { afterEach, describe, expect, it } from "vitest"
import { cleanup, render, screen } from "@testing-library/react"
import { contornoDoSinete, SeloOficial } from "./SeloOficial.js"
import { strings } from "../strings.js"

afterEach(cleanup)

/**
 * The common channel seal, now a symbol instead of a word.
 *
 * Two test groups, and the split is not arbitrary. The first guards
 * ACCESSIBILITY, which is what moving from word to symbol puts at risk: a word
 * reads itself, a drawing does not, and the regression would be silent because
 * sight would not show it. The second guards GEOMETRY, which is generated by
 * code. A broken calculation produces a plausible `d` instead of breaking.
 */
describe("selo oficial — a palavra que o símbolo não pode levar consigo", () => {
  it("anuncia-se por palavras a quem não vê o desenho", () => {
    render(<SeloOficial />)
    // The same text as when the seal WAS text: those who hear keep hearing what
    // those who see stopped reading.
    expect(screen.getByRole("img", { name: strings.oficial.selo })).toBeTruthy()
  })

  it("continua a explicar de onde vem a oficialidade, e não só a afirmá-la", () => {
    render(<SeloOficial />)
    const selo = screen.getByRole("img", { name: strings.oficial.selo })
    expect(selo.getAttribute("title")).toBe(strings.oficial.seloTitle)
    // The phrase must keep saying that the SERVER points to the channel. A seal
    // that only asserts itself is what teaches people to trust seals.
    expect(strings.oficial.seloTitle).toContain("servidor")
  })

  it("o desenho não fala duas vezes: quem anuncia é o `<span>`", () => {
    const { container } = render(<SeloOficial />)
    expect(container.querySelector("svg")?.getAttribute("aria-hidden")).toBe("true")
  })

  it("veste a cor do sistema por herança, para o `--accent` viver no CSS", () => {
    const { container } = render(<SeloOficial />)
    const [sinete] = container.querySelectorAll("path")
    expect(sinete?.getAttribute("fill")).toBe("currentColor")
  })
})

describe("selo oficial — a geometria do sinete", () => {
  it("é um contorno fechado de um arco por lobo", () => {
    const contorno = contornoDoSinete()
    expect(contorno.startsWith("M")).toBe(true)
    expect(contorno.endsWith("Z")).toBe(true)
    expect(contorno.match(/A/g)).toHaveLength(12)
  })

  it("cabe na caixa de 24, que é a grelha de toda a família de ícones", () => {
    // A wolf leaving the box gets clipped by `viewBox` with no warning: the
    // drawing appears with a flattened side and nobody knows why.
    for (const numero of contornoDoSinete().match(/-?\d+(\.\d+)?/g) ?? []) {
      const valor = Number(numero)
      expect(valor).toBeGreaterThanOrEqual(0)
      expect(valor).toBeLessThanOrEqual(24)
    }
  })

  it("os arcos encontram-se todos à mesma distância do centro", () => {
    // It is the invariant that says this is a rosette and not a blotch: if the
    // crossings are not on a circle, the wolves have different depths from each
    // other and the seal twists on one side.
    const raios = cruzamentos()
    // Thirteen not twelve: the point of the `M` is the same as the end of the last
    // arc, and appears in both places because a closed path begins where it ends.
    expect(raios).toHaveLength(13)
    for (const raio of raios) expect(raio).toBeCloseTo(raios[0] ?? 0, 1)
  })

  it("o recorte é fundo o suficiente para se ver, e raso o suficiente para não picar", () => {
    // Below ~5% the seal reads as a circle at 14 pixels; above ~20% the wolves get
    // pointed and the drawing becomes a star.
    const fundura = (11 - (cruzamentos()[0] ?? 0)) / 11
    expect(fundura).toBeGreaterThan(0.05)
    expect(fundura).toBeLessThan(0.2)
  })
})

/**
 * How far from the center each point where two arcs meet is.
 *
 * It reads the `d` instead of repeating the component's calculation, on
 * purpose. A second copy of the trigonometry would prove that two equal
 * calculations give the same result, which is not interesting. This way what
 * gets measured is the drawing that comes out.
 */
function cruzamentos(): number[] {
  return [...contornoDoSinete().matchAll(/(\d+\.?\d*) (\d+\.?\d*)(?:A|Z)/g)].map(([, x, y]) =>
    Math.hypot(Number(x) - 12, Number(y) - 12),
  )
}
