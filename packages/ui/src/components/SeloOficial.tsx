import { strings } from "../strings.js"

/**
 * The common channel seal: a signet clipped with a checkmark inside.
 *
 * It was the word "official", and the comment that was here defended it: the
 * blue checkmark on other networks says "this identity was confirmed by
 * someone", and here nobody confirmed anything. The argument stays true. What
 * changed was who decides. The owner asked for the symbol, and the defense
 * against misunderstanding is not the word: it is the `title`, which still says
 * in full where the official status comes from and what it is not.
 *
 * What did NOT change, and is the half that matters: this is still not a field.
 * Who orders this seal drawn is `lib/oficial.ts`, comparing the channel with
 * what the server announced in `hello.ok`. There is no `official: true` in any
 * metadata, and the temptation to invent it grew now that the seal is pretty. A
 * seal that any client writes to itself distinguishes nothing.
 *
 * **Color is system color** (`--accent`, see `usePrefs`), and it is the only
 * place in the app where chosen color appears as brand and not as state. On
 * purpose: the seal says "this is home", and home has the color the person gave
 * it. States (connected, busy, ringing) never use `--accent`, for the reason
 * written in `tokens.css`.
 *
 * **No word, no reading.** A symbol is invisible to screen reader users, so the
 * accessible name is the same word that was written here, and the explanation
 * is the same `title` as always. The `<svg>` is `aria-hidden`: the `<span>`
 * announces it once instead of twice.
 */

/** How many wolves the clip has. */
const LOBOS = 12

/** Half of the 24 box, which is the grid for the entire icon family. */
const CENTRO = 12

/** How far a wolf point reaches. A hair below 12, to avoid touching the edge. */
const RAIO = 11

/**
 * The depth of the clip, as a fraction of the wolf radius over the rest.
 *
 * It is the only number with taste in there, and it is what separates a signet
 * from a flower: at 0.26 the wolves get pointed and the drawing becomes a star,
 * above 0.45 the waves flatten and at 14 pixels it looks like a circle. At 0.34
 * the clip eats 11.5% of the radius, which shows at 14 pixels and makes no
 * noise at 56.
 */
const RAZAO_DO_LOBO = 0.34

/**
 * The outline of the signet: twelve arcs, nothing more.
 *
 * Built the usual way for a rosette: twelve equal circles spread around a ring,
 * and the outline is the part of each that stays outside its neighbors. They
 * OVERLAP on purpose: tangent, they would meet at a point and the drawing would
 * be a twelve-pointed star. Overlapped, they meet where they cross, and the
 * crossing is the wave between wolves.
 *
 * Generated by code instead of drawn by hand because a 336-character `d` is a
 * number nobody checks: changing the depth would mean redrawing everything, and
 * someone reading the file could not tell if the drawing is right. Runs once at
 * module load, not per render.
 *
 * `scripts/selo-geometria.mjs` prints this outside React, so numbers can be
 * checked without building the app.
 */
export function contornoDoSinete(lobos = LOBOS, raio = RAIO, razao = RAZAO_DO_LOBO): string {
  // The wolf and the ring split the radius between them: wolf point = ring + wolf.
  const lobo = (raio * razao) / (1 + razao)
  const anel = raio - lobo
  const passo = (Math.PI * 2) / lobos

  /**
   * How far apart two neighboring wolves cross.
   *
   * Both centers are at `ring` from the center, so the perpendicular bisector
   * of the segment joining them passes through the center. The two crossings lie
   * on it, each at half the distance plus or minus the missing leg. We want the
   * outer one.
   */
  const meiaCorda = anel * Math.sin(passo / 2)
  const cruzamento = anel * Math.cos(passo / 2) + Math.sqrt(lobo * lobo - meiaCorda * meiaCorda)

  // Two decimal places: the difference in the third is 0.006 pixels at 14, and
  // the `d` would be half longer to see nothing.
  const arredondar = (valor: number): string => (Math.round(valor * 100) / 100).toString()
  /** The crossing between wolf `i` and the next one, in the middle of both. */
  const encontro = (i: number): string => {
    const angulo = (i + 0.5) * passo
    return `${arredondar(CENTRO + cruzamento * Math.cos(angulo))} ${arredondar(CENTRO + cruzamento * Math.sin(angulo))}`
  }

  // Each arc is wolf `i`, from the previous crossing to the next, on the outside.
  // Less than half a circle (129°, with these numbers), so `large-arc` is zero.
  // Direction of growing angle, which with y pointing down is clockwise, so
  // `sweep` is one.
  let contorno = `M${encontro(lobos - 1)}`
  for (let i = 0; i < lobos; i++) contorno += `A${arredondar(lobo)} ${arredondar(lobo)} 0 0 1 ${encontro(i)}`
  return `${contorno}Z`
}

const SINETE = contornoDoSinete()

/**
 * The checkmark, in stroke not clipped.
 *
 * Clipped, a hole in the seal showing the background, would be more true to a
 * wax seal and was the first idea. It fails for a measured reason: the seal
 * appears in the sidebar, which changes background on hover and when open, and
 * a hole changes color with it. In stroke, the checkmark has the color it has.
 *
 * `--bg-deep` as ink, not `--on-accent`: the white of `--on-accent` is only
 * readable on the DARK tones of the system, and here the background is light
 * `--accent`. With Lilac it gave 2.5:1. Against `--bg-deep` all five tones give
 * from 5.9:1 (Lilac) to 12.5:1 (Mint), all above the 3:1 a graphic object asks.
 *
 * Same thickness and same rounded ends as the `SidebarIcons` family, a bit
 * thicker because this stroke is small and lives inside another shape.
 */
const VISTO = "M7.4 12.4 10.5 15.5 16.6 9.4"

export function SeloOficial(): React.JSX.Element {
  return (
    /*
      Name and explanation go in the `<span>`, not in the `<svg>`.

      `role="img"` with `aria-label` because content no longer has text: without
      this, screen reader users heard the channel name and nothing else, and the
      official status, which is exactly what is announced here, disappeared. The
      `title` is what it was, with the same sentence, and stays what cannot be
      cut: a seal without explanation is what teaches people to trust seals.
    */
    <span className="selo-oficial" role="img" aria-label={strings.oficial.selo} title={strings.oficial.seloTitle}>
      <svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">
        {/* `currentColor` so color lives in CSS, where `--accent` lives. */}
        <path d={SINETE} fill="currentColor" />
        <path
          d={VISTO}
          fill="none"
          stroke="var(--bg-deep)"
          strokeWidth={2.6}
          strokeLinecap="round"
          strokeLinejoin="round"
        />
      </svg>
    </span>
  )
}
