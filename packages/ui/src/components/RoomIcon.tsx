/**
 * The icon of a channel: the image they gave it, or the initial over a color
 * derived from the identifier.
 *
 * The generated color is still what you see in the overwhelming majority of
 * cases, and that is on purpose: the same channel gives the same color on any
 * device, with nothing to load or sync. The image is the luxury, not the rule.
 *
 * The comment that was here said that channel images would need a new payload
 * type and a decision about who can change them. Both happened: the payload is
 * `space.meta` and the decision is made, today any member, and from roles on
 * only those with the right.
 */

import { OrwellMark } from "../icons.js"

/** Deterministic hue from the channel id. Stable across devices by being math. */
export function roomHue(channel: string): number {
  let hash = 0
  for (const char of channel) hash = (hash * 31 + (char.codePointAt(0) ?? 0)) >>> 0
  return hash % 360
}

export function RoomIcon({
  channel,
  label,
  size = 24,
  icon,
  round = false,
  official = false,
}: {
  channel: string
  label: string
  size?: number
  /** Data URL published in `space.meta`. Without it, the initial. */
  icon?: string | undefined
  /**
   * The common channel the server announces. See `lib/oficial.ts`.
   *
   * Does not come from the channel metadata on purpose, it comes from above,
   * from whoever compared this channel with what the server announced. An
   * `official` read from `space.meta` would be exactly the forgeable seal we
   * do not want.
   */
  official?: boolean
  /**
   * Circle instead of rounded square: a person, not a channel.
   *
   * It signals the nature of the line rather than borrowing a symbol (the `@`
   * that was here) from a different visual language than the rest of the list.
   * Circles mean people everywhere, and alignment with other lines becomes exact
   * because the box is the same.
   */
  round?: boolean
}): React.JSX.Element {
  if (icon) {
    return (
      <span
        className="room-icon"
        aria-hidden="true"
        style={{ width: size, height: size, ...(round ? { borderRadius: "50%" } : {}) }}
      >
        <img src={icon} alt="" />
      </span>
    )
  }

  /**
   * The official channel uses the app's brand instead of a colored initial.
   *
   * The initial came from the name and the color from the identifier: the first
   * thing a newcomer saw was a square generated by a hash function. Here there
   * is a drawn icon, and it comes after the `icon` above on purpose. If someone
   * inside publishes an icon, that is what shows, like any other channel.
   */
  if (official) {
    return (
      <span className="room-icon official" aria-hidden="true" style={{ width: size, height: size }}>
        <OrwellMark size={Math.round(size * 0.72)} />
      </span>
    )
  }

  return (
    <span
      className="room-icon"
      aria-hidden="true"
      style={{
        width: size,
        height: size,
        fontSize: Math.round(size * 0.5),
        // 34% lightness keeps near-white text at AA on every hue, yellows included.
        background: `hsl(${roomHue(channel)} 42% 34%)`,
        ...(round ? { borderRadius: "50%" } : {}),
      }}
    >
      {label[0]?.toUpperCase() ?? "#"}
    </span>
  )
}
