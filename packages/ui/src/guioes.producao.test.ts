import { existsSync, readdirSync, readFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { describe, expect, it } from "vitest"

/**
 * No script writes production by hand.
 *
 * Scripts create accounts, rooms and calls. Against production that is noise on top
 * of people actually talking, and it has cost data twice: on August 6, 2026 a load
 * race erased the owner's publication record he had just posted, and on August 13
 * I created two throwaway accounts in production because `e2e-dm.mjs` had `orwell.pt`
 * as its default value.
 *
 * After that, `scripts/ambiente.mjs` refused production without
 * `ORWELL_PERMITIR_PRODUCAO=sim`. But a lock is only worth as much as it is the only
 * path: eight scripts had `page.goto("https://orwell.pt")` written by hand and passed
 * it by without any effort. One of them was caught trying to create accounts in
 * production after the lock was in place.
 *
 * This test closes that door. It is not about style: it is about the only defense
 * against repeating a data loss that already happened.
 *
 * When it fails: the script starts requesting the target from `ambiente.mjs`,  * `alvo()` for the server name, `alvoApp()` or `APP` for the page. Do not add an
 * exception here.
 */

/**
 * The scripts folder, found by walking up.
 *
 * `process.cwd()` is not reliable here: `npm test` runs `vitest --root packages/ui`
 * from the monorepo root, and a path relative to cwd escapes the repository. This
 * test started failing only in that invocation form, green running the package
 * directly, red in the suite. Walking up until finding the file is the only way
 * that works in both.
 */
function pastaDosGuioes(): string {
  let aqui = process.cwd()
  for (let salto = 0; salto < 6; salto++) {
    const candidato = join(aqui, "scripts")
    if (existsSync(join(candidato, "ambiente.mjs"))) return candidato
    aqui = dirname(aqui)
  }
  throw new Error("não encontrei scripts/ambiente.mjs a subir a partir de " + process.cwd())
}

const GUIOES = pastaDosGuioes()

/** Where the lock lives. It is the only file that can name production. */
const A_TRANCA = "ambiente.mjs"

function guioes(): { nome: string; texto: string }[] {
  return readdirSync(GUIOES)
    .filter((nome) => nome.endsWith(".mjs") && nome !== A_TRANCA)
    .map((nome) => ({ nome, texto: readFileSync(join(GUIOES, nome), "utf8") }))
}

/**
 * Mentions production outside a comment?
 *
 * Comments talk about it all the time, and they should: half these files tell the
 * story of a race that went wrong. What cannot happen is code doing it.
 */
function mencionaProducaoEmCodigo(texto: string): string[] {
  const achados: string[] = []
  for (const [numero, linha] of texto.split("\n").entries()) {
    const limpa = linha.trim()
    if (limpa.startsWith("*") || limpa.startsWith("//") || limpa.startsWith("/*")) continue
    // Writing the address on the screen is not pointing to it. The script that publishes
    // installers says where it put them, and must say it.
    if (/^console\.(log|error|warn)\(/.test(limpa)) continue
    // An email address is not a target: `nome@orwell.pt` is where you write, not where
    // a script connects. What this test catches are scripts pointed at production, and
    // a `mailto:` does not point anywhere.
    if (/mailto:[^"'`\s]*orwell\.pt/.test(limpa) && !/https?:\/\/[^"'`\s]*orwell\.pt/.test(limpa)) continue
    /*
      A `canonical`, an `alternate` with `hreflang` or a sharing meta tag INSIDE HTML
      generated by a script are declarations about the page, not places where the
      script connects. `publicar-instaladores.mjs` writes the download page: it has
      to say what its address is in production, because that is where it will live.
      */
    if (/rel="canonical"|rel="alternate" hreflang=|property="og:|name="twitter:/.test(limpa)) continue
    if (/orwell\.pt/.test(limpa)) achados.push(`${numero + 1}: ${limpa.slice(0, 90)}`)
  }
  return achados
}

describe("guiões e produção", () => {
  it("nenhum guião nomeia orwell.pt em código", () => {
    const infractores: string[] = []
    for (const { nome, texto } of guioes()) {
      for (const linha of mencionaProducaoEmCodigo(texto)) infractores.push(`${nome}:${linha}`)
    }

    expect(infractores, `produção escrita à mão:\n${infractores.join("\n")}`).toEqual([])
  })

  it("e a tranca continua a exigir uma afirmação no ambiente", () => {
    // If someone swaps the variable for an argument, this breaks, and it should. An
    // argument gets copied from an old command line without reading it; an environment
    // variable is set on purpose.
    const tranca = readFileSync(join(GUIOES, A_TRANCA), "utf8")
    expect(tranca).toContain("ORWELL_PERMITIR_PRODUCAO")
    expect(tranca).toContain("process.exit(2)")
  })
})
